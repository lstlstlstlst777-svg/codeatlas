"""生成"节点很多"的 C fixture（ISSUE-012）。

为什么需要它：ISSUE-001（tree-sitter ABI 错位）只在 200+ 顶层节点后才暴露，
而当时所有 fixture 都只有几十行，单测全绿却掩盖了致命 bug。
这个 fixture 的作用是让"错位"在毫秒级的单测里重现，不必等 Redis 全量用例。

生成方式刻意保持规整：每个函数 3 行、注释写清序号，
这样一旦行号偏了，报错信息里的函数名就能直接定位到第几个节点。

用法：
    python scripts/gen_fixture.py            # 写到 tests/fixtures/c/many_nodes.c
"""

from __future__ import annotations

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TARGET = REPO_ROOT / "tests" / "fixtures" / "c" / "many_nodes.c"

# 必须超过 200 个顶层节点：ISSUE-001 的错位就是从第 52 个节点开始、
# 在更大的文件里表现为行号变成 0x40000000+n。留足余量。
FUNCTION_COUNT = 260
MACRO_COUNT = 40
STRUCT_COUNT = 20


def build() -> str:
    lines: list[str] = [
        "/* Auto-generated by scripts/gen_fixture.py — do not edit by hand.",
        " *",
        " * 用途：让 tree-sitter 的节点错位问题在单测里可复现（见 docs/ISSUES.md ISSUE-001/012）。",
        f" * 规模：{FUNCTION_COUNT} 个函数 + {MACRO_COUNT} 个宏 + {STRUCT_COUNT} 个结构体，",
        " * 远超 200 个顶层节点。每行都带序号，行号偏了能一眼看出来。",
        " */",
        "",
        "#include <stddef.h>",
        "#include <string.h>",
        "",
    ]

    for i in range(MACRO_COUNT):
        lines.append(f"#define MANY_MACRO_{i:03d} ({i} * 3 + 1)")
    lines.append("")

    for i in range(STRUCT_COUNT):
        lines.append(f"struct many_struct_{i:03d} {{")
        lines.append(f"    int field_a_{i:03d};")
        lines.append(f"    const char *field_b_{i:03d};")
        lines.append("};")
        lines.append("")

    for i in range(FUNCTION_COUNT):
        lines.append(f"/* function index {i:03d} — 行号错位时请看这个序号 */")
        lines.append(f"int many_func_{i:03d}(int value) {{")
        lines.append(f"    return value + {i};")
        lines.append("}")
        lines.append("")

    lines.append("int many_nodes_entry(int value) {")
    lines.append("    int total = 0;")
    lines.append("    for (int i = 0; i < 1; i++) {")
    lines.append("        total += many_func_000(value);")
    lines.append("    }")
    lines.append("    (void)MANY_MACRO_000;")
    lines.append("    return total;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = build()
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    line_count = text.count("\n")
    top_level = FUNCTION_COUNT + MACRO_COUNT + STRUCT_COUNT + 1
    print(f"wrote {TARGET}")
    print(f"lines={line_count}  approx_top_level_nodes={top_level}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
